def main():
    book = Workbook()
    book.remove(book.active)
    for name, rows in DATA.items():
        sheet = book.create_sheet(name)
        for row in rows:
            sheet.append(row)
        sheet.freeze_panes = "A2"
        sheet.auto_filter.ref = sheet.dimensions
        for cell in sheet[1]:
            cell.font = Font(bold=True, color="FFFFFF")
            cell.fill = PatternFill("solid", fgColor="008080")
        for col in sheet.columns:
            width = min(40, max(12, max(len(str(c.value or "")) for c in col) + 2))
            sheet.column_dimensions[get_column_letter(col[0].column)].width = width
    book.save(OUTPUT)
    print("Создан демонстрационный файл:", OUTPUT)


if __name__ == "__main__":
    main()
