-- КИМ 09.02.07-2-2027, стр. 30-31 (образец ДЭ в рамках ПА)
-- СУБД: Microsoft Access (диалект Jet/ACE SQL)
-- Третья нормальная форма, ссылочная целостность,
-- ограничения внешних ключей ON UPDATE CASCADE / ON DELETE CASCADE.
--
-- Примечание: поле «Изображение» в итоговой .accdb имеет тип «Вложение»
-- (ATTACHMENT). Jet SQL DDL не умеет создавать ATTACHMENT, поэтому здесь
-- оно объявлено LONGBINARY (OLE), а финальный тип выставляет
-- tools/СборкаБД.ps1 (DAO). Данные INSERT — источник данных для сборки.
-- =====================================================================

-- ---------- ТАБЛИЦЫ ----------

CREATE TABLE Клиенты (
  ID_Клиента COUNTER CONSTRAINT PK_Клиенты PRIMARY KEY,
  ФИО TEXT(100) NOT NULL,
  Логин TEXT(50),
  Телефон TEXT(20)
);

CREATE TABLE Категории (
  ID_Категории COUNTER CONSTRAINT PK_Категории PRIMARY KEY,
  Наименование TEXT(50) NOT NULL
);

CREATE TABLE Производители (
  ID_Производителя COUNTER CONSTRAINT PK_Производители PRIMARY KEY,
  Наименование TEXT(50) NOT NULL,
  Страна TEXT(50)
);

CREATE TABLE Модели (
  ID_Модели COUNTER CONSTRAINT PK_Модели PRIMARY KEY,
  Наименование TEXT(100) NOT NULL,
  ID_Категории LONG NOT NULL,
  ID_Производителя LONG NOT NULL,
  Состав TEXT(100),
  Описание MEMO,
  Цена CURRENCY,
  Изображение LONGBINARY
  -- Правила проверки (Цена >= 0 и др.) задаются свойством ValidationRule
  -- полей — см. tools/СборкаБД.ps1 и режим конструктора Access.
);

CREATE TABLE ТоварныеПозиции (
  ID_Позиции COUNTER CONSTRAINT PK_ТоварныеПозиции PRIMARY KEY,
  ID_Модели LONG NOT NULL,
  Размер BYTE,
  Количество LONG
);

CREATE TABLE Заказы (
  ID_Заказа COUNTER CONSTRAINT PK_Заказы PRIMARY KEY,
  ID_Клиента LONG NOT NULL,
  ДатаЗаказа DATETIME
);

CREATE TABLE СоставЗаказа (
  ID_Строки COUNTER CONSTRAINT PK_СоставЗаказа PRIMARY KEY,
  ID_Заказа LONG NOT NULL,
  ID_Позиции LONG NOT NULL,
  Количество LONG,
  ЦенаЗаЕдиницу CURRENCY
);

-- Ограничение предметной области: одна модель в одном размере —
-- только одна товарная позиция (сочетание модель + размер уникально).
CREATE UNIQUE INDEX UX_МодельРазмер ON ТоварныеПозиции (ID_Модели, Размер);

-- ---------- СВЯЗИ (ссылочная целостность) ----------
-- Родитель → Дочерняя: ПК → ВК.
-- Каскадное удаление — только у Заказы→СоставЗаказа (удаление заказа
-- удаляет его строки). У остальных — запрет удаления «родителя» с данными.
-- Примечание: при сборке .accdb скриптом tools/СборкаБД.ps1 связи создаются
-- методом DAO CreateRelation с теми же атрибутами (эти операторы ADD CONSTRAINT
-- выполняются в ADO/ANSI-92; DAO Execute их не принимает).

ALTER TABLE Заказы ADD CONSTRAINT R_Клиенты_Заказы
  FOREIGN KEY (ID_Клиента) REFERENCES Клиенты (ID_Клиента)
  ON UPDATE CASCADE;

ALTER TABLE СоставЗаказа ADD CONSTRAINT R_Заказы_СоставЗаказа
  FOREIGN KEY (ID_Заказа) REFERENCES Заказы (ID_Заказа)
  ON UPDATE CASCADE ON DELETE CASCADE;

ALTER TABLE СоставЗаказа ADD CONSTRAINT R_Позиции_СоставЗаказа
  FOREIGN KEY (ID_Позиции) REFERENCES ТоварныеПозиции (ID_Позиции)
  ON UPDATE CASCADE;

ALTER TABLE ТоварныеПозиции ADD CONSTRAINT R_Модели_Позиции
  FOREIGN KEY (ID_Модели) REFERENCES Модели (ID_Модели)
  ON UPDATE CASCADE;

ALTER TABLE Модели ADD CONSTRAINT R_Категории_Модели
  FOREIGN KEY (ID_Категории) REFERENCES Категории (ID_Категории)
  ON UPDATE CASCADE;

ALTER TABLE Модели ADD CONSTRAINT R_Производители_Модели
  FOREIGN KEY (ID_Производителя) REFERENCES Производители (ID_Производителя)
  ON UPDATE CASCADE;

